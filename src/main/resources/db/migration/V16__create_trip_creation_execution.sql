CREATE TABLE trip_creation_executions (
    execution_id VARCHAR(36) NOT NULL PRIMARY KEY,
    trip_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'UPLOADING',
    total_attachment_count INT NOT NULL,
    input_closed BOOLEAN NOT NULL DEFAULT FALSE,
    last_upload_activity_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    process_published_at DATETIME(6),
    reserved_bytes BIGINT NOT NULL DEFAULT 0,
    accounted_bytes BIGINT NOT NULL DEFAULT 0,
    reservation_released BOOLEAN NOT NULL DEFAULT FALSE,
    process_outbox_id VARCHAR(36),
    process_payload LONGTEXT,
    process_delivery_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    process_attempts INT NOT NULL DEFAULT 0,
    process_claim_token VARCHAR(36),
    process_lease_until DATETIME(6),
    process_next_attempt_at DATETIME(6),
    result_raw_payload LONGTEXT,
    result_ai_status VARCHAR(20),
    result_received_at DATETIME(6),
    result_conflicts LONGTEXT,
    result_attempts INT NOT NULL DEFAULT 0,
    result_attempt_started_at DATETIME(6),
    result_failed_at DATETIME(6),
    result_failure_reason VARCHAR(255),
    result_claim_token VARCHAR(36),
    result_lease_until DATETIME(6),
    result_next_attempt_at DATETIME(6),
    ended_at DATETIME(6),
    error_code VARCHAR(100),
    cancel_pending BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_trip_creation_execution_trip UNIQUE (trip_id),
    CONSTRAINT fk_trip_creation_execution_trip FOREIGN KEY (trip_id) REFERENCES trips (trip_id),
    CONSTRAINT fk_trip_creation_execution_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_trip_creation_execution_bytes CHECK (reserved_bytes >= 0 AND accounted_bytes >= 0),
    INDEX idx_trip_execution_upload_timeout (status, input_closed, last_upload_activity_at),
    INDEX idx_trip_execution_result (status, result_next_attempt_at, result_lease_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

